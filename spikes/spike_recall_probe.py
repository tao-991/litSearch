"""Recall probe: is a known paper indexed by each source, and which queries surface it (rank)?

    uv run --python 3.12 spikes/spike_recall_probe.py 2506.11009 "human-in-the-loop software development"

Serial, small. OpenAlex search costs ~10 credits per request.
"""

from __future__ import annotations

import asyncio
import json
import os
import sys
from pathlib import Path

import httpx

sys.path.insert(0, str(Path(__file__).parent))
from _common import QUERIES, Source, load_env, save_sample
from spike_arxiv import ARXIV_QUERIES, parse_feed
from spike_arxiv import BASE as ARXIV

OA = "https://api.openalex.org"
S2 = "https://api.semanticscholar.org/graph/v1"

ALT = {
    "alt1": "human-in-the-loop software development agents",
    "alt2": "human-AI collaboration coding agents challenges",
    "alt3": "developers review code generated by AI agents",
    "alt4": "software engineering agents human oversight",
}
ALT_ARXIV = {
    "alt1": 'all:"human-in-the-loop" AND all:agents AND all:"software development"',
    "alt2": 'all:"coding agent" AND all:human',
    "alt3": 'all:"software engineering" AND all:agents AND (all:review OR all:oversight)',
}


async def main(arxiv_id: str, title_words: str) -> None:
    load_env()
    email = os.environ.get("CONTACT_EMAIL")
    secret = {"mailto": email} if email else {}
    out: dict = {"target": arxiv_id}
    async with httpx.AsyncClient(
        timeout=30, follow_redirects=True, headers={"User-Agent": "litsearch-spike/0.1"}
    ) as c:
        # 1. arXiv: does it exist, what are its fields
        ax = Source("arxiv", c, 3.0)
        r = await ax.get(ARXIV, "id_list", params={"id_list": arxiv_id})
        if r is not None and r.status_code == 200:
            _, ents = parse_feed(r.text)
            e = ents[0] if ents else {}
            out["arxiv_entry"] = {
                k: e.get(k)
                for k in (
                    "id",
                    "title",
                    "published",
                    "doi",
                    "journal_ref",
                    "comment",
                    "primary_category",
                )
            }
            out["arxiv_abstract_head"] = (e.get("summary") or "")[:300]

        # 2. OpenAlex: indexed? venue info?
        oa = Source("openalex", c, 0.3)
        r = await oa.get(
            f"{OA}/works/doi:10.48550/arxiv.{arxiv_id}",
            "oa_lookup",
            params={
                "select": "id,title,type,publication_year,doi,primary_location,locations,abstract_inverted_index,cited_by_count"
            },
            secret_params=secret,
        )
        if r is not None and r.status_code == 200:
            w = r.json()
            out["openalex"] = {
                "id": w["id"],
                "title": w["title"],
                "type": w["type"],
                "year": w["publication_year"],
                "doi": w["doi"],
                "has_abstract": bool(w.get("abstract_inverted_index")),
                "cited_by": w.get("cited_by_count"),
                "locations": [
                    (l.get("source") or {}).get("display_name")
                    or l.get("landing_page_url")
                    for l in w.get("locations", [])
                ],
            }
            target_oa = w["id"]
        else:
            out["openalex"] = {"status": r.status_code if r else None}
            target_oa = None

        # 3. S2: indexed? (single try, no retry)
        s2 = Source("s2", c, 1.0)
        r = await s2.get(
            f"{S2}/paper/ARXIV:{arxiv_id}",
            "s2_lookup",
            params={"fields": "title,year,venue,publicationVenue,externalIds"},
            retry=False,
        )
        out["s2"] = (
            r.json()
            if (r is not None and r.status_code == 200)
            else {"status": s2.log[-1].get("status")}
        )

        # 4. rank in OpenAlex search (top 50) for our 3 queries + alternatives
        out["openalex_rank"] = {}
        for qid, q in {**QUERIES, **ALT}.items():
            r = await oa.get(
                f"{OA}/works",
                f"rank:{qid}",
                params={"search": q, "per-page": 50, "select": "id,title"},
                secret_params=secret,
            )
            rank = None
            total = None
            if r is not None and r.status_code == 200:
                b = r.json()
                total = b["meta"]["count"]
                ids = [w["id"] for w in b["results"]]
                rank = ids.index(target_oa) + 1 if target_oa in ids else None
            out["openalex_rank"][qid] = {
                "query": q,
                "total_matches": total,
                "rank_in_top50": rank,
            }

        # 5. rank in arXiv search (top 50)
        out["arxiv_rank"] = {}
        for qid, q in {**ARXIV_QUERIES, **ALT_ARXIV}.items():
            r = await ax.get(
                ARXIV,
                f"rank:{qid}",
                params={
                    "search_query": q,
                    "start": 0,
                    "max_results": 50,
                    "sortBy": "relevance",
                    "sortOrder": "descending",
                },
            )
            rank = None
            total = None
            if r is not None and r.status_code == 200:
                meta, ents = parse_feed(r.text)
                total = meta["totalResults"]
                ids = [e["id"] for e in ents]
                rank = next((i + 1 for i, x in enumerate(ids) if arxiv_id in x), None)
            out["arxiv_rank"][qid] = {
                "query": q,
                "total_matches": total,
                "rank_in_top50": rank,
            }
    save_sample("recall_probe.json", out)
    print(json.dumps(out, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    asyncio.run(main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else ""))
