"""Turn spikes/samples/* raw responses into a human-readable Markdown file.

    python3 spikes/make_readable.py   ->  spikes/samples/readable.md

Only fields returned by the sources are shown (no generated text).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from _common import QUERIES, SAMPLES
from spike_arxiv import ARXIV_QUERIES, parse_feed
from spike_openalex import reconstruct_abstract


def esc(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def authors_str(names: list[str]) -> str:
    names = [n for n in names if n]
    return ", ".join(names[:3]) + (
        f" et al. ({len(names)} authors)" if len(names) > 3 else ""
    )


def render(title: str, query: str, rows: list[dict]) -> str:
    out = [f"### {title}", f"Query: `{query}`  ·  {len(rows)} papers", ""]
    out += [
        "| # | Title | Year | Authors | Abstract | Links |",
        "|---|---|---|---|---|---|",
    ]
    for i, r in enumerate(rows, 1):
        links = " · ".join(f"[{k}]({v})" for k, v in r["links"].items() if v)
        out.append(
            f"| {i} | {esc(r['title'] or '(no title)')} | {r['year'] or ''} | {esc(authors_str(r['authors']))} "
            f"| {'yes' if r['abstract'] else 'no'} | {links} |"
        )
    out.append("")
    out.append("<details><summary>Full abstracts</summary>\n")
    for i, r in enumerate(rows, 1):
        out.append(
            f"**{i}. {esc(r['title'] or '')}**\n\n{r['abstract'] or '(no abstract)'}\n"
        )
    out.append("</details>\n")
    return "\n".join(out)


def openalex_rows(path: Path) -> list[dict]:
    rows = []
    for w in json.loads(path.read_text()).get("results", []):
        loc = w.get("best_oa_location") or {}
        links = {
            "DOI": w.get("doi"),
            "OA PDF": loc.get("pdf_url"),
            "OpenAlex": w.get("id"),
        }
        rows.append(
            {
                "title": w.get("title"),
                "year": w.get("publication_year"),
                "authors": [
                    (a.get("author") or {}).get("display_name")
                    for a in w.get("authorships", [])
                ],
                "abstract": reconstruct_abstract(w.get("abstract_inverted_index")),
                "links": links,
            }
        )
    return rows


def s2_rows(path: Path) -> list[dict]:
    try:
        data = json.loads(path.read_text()).get("data", [])
    except ValueError:
        return []
    rows = []
    for p in data:
        ext = p.get("externalIds") or {}
        links = {
            "DOI": f"https://doi.org/{ext['DOI']}" if ext.get("DOI") else None,
            "arXiv": f"https://arxiv.org/abs/{ext['ArXiv']}"
            if ext.get("ArXiv")
            else None,
            "OA PDF": (p.get("openAccessPdf") or {}).get("url"),
            "S2": p.get("url"),
        }
        rows.append(
            {
                "title": p.get("title"),
                "year": p.get("year"),
                "authors": [a.get("name") for a in p.get("authors", [])],
                "abstract": p.get("abstract"),
                "links": links,
            }
        )
    return rows


def arxiv_rows(path: Path) -> list[dict]:
    _, entries = parse_feed(path.read_text())
    return [
        {
            "title": e["title"],
            "year": (e["published"] or "")[:4],
            "authors": e["authors"],
            "abstract": e["summary"],
            "links": {
                "arXiv": e["links"].get("alternate"),
                "PDF": e["links"].get("pdf"),
                "DOI": f"https://doi.org/{e['doi']}" if e["doi"] else None,
            },
        }
        for e in entries
    ]


def gscholar_rows(path: Path) -> list[dict]:
    rows = []
    for r in json.loads(path.read_text()):
        b = r.get("bib", {})
        ep = r.get("eprint_url") or ""
        links = {
            "publisher page": r.get("pub_url"),
            "eprint": ep if ep.startswith("http") else None,
        }
        rows.append(
            {
                "title": b.get("title"),
                "year": b.get("pub_year") if b.get("pub_year") != "NA" else "",
                "authors": b.get("author") or [],
                "abstract": b.get(
                    "abstract"
                ),  # search snippet only, not a full abstract
                "links": links,
            }
        )
    return rows


def main() -> None:
    parts = [
        "# Phase 0 search results (readable)",
        "",
        "Generated by `spikes/make_readable.py` from the raw responses; every field comes from the data source, nothing is rewritten by a model.",
        "",
    ]
    for qid, q in QUERIES.items():
        parts.append(f"## {qid}: {q}\n")
        for name, fn, path, query in (
            ("OpenAlex", openalex_rows, SAMPLES / f"openalex_search_{qid}.json", q),
            ("Semantic Scholar", s2_rows, SAMPLES / f"s2_search_{qid}.json", q),
            (
                "arXiv",
                arxiv_rows,
                SAMPLES / f"arxiv_search_{qid}.xml",
                ARXIV_QUERIES[qid],
            ),
            (
                "Google Scholar (abstract column is only a search snippet)",
                gscholar_rows,
                SAMPLES / f"gscholar_search_{qid}.json",
                q,
            ),
        ):
            rows = fn(path) if path.exists() else []
            if rows:
                parts.append(render(name, query, rows))
            else:
                parts.append(
                    f"### {name}\n\n(no data: request was rate-limited or the file is missing)\n"
                )
    out = SAMPLES / "readable.md"
    out.write_text("\n".join(parts))
    print(out)


if __name__ == "__main__":
    main()
