"""Data shapes shared by all collectors (SPEC §4)."""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Any


@dataclass(frozen=True, slots=True)
class PaperMeta:
    """One paper as reported by one data source.

    Every field except ``source`` / ``source_id`` is copied or derived
    deterministically from what the source returned; nothing is generated by a model.
    ``doi`` and ``arxiv_id`` are normalized (see ``litsearch.normalize``).
    """

    source: str
    source_id: str
    title: str
    abstract: str | None = None
    authors: tuple[str, ...] = ()
    year: int | None = None
    date: str | None = None
    venue: str | None = None
    doi: str | None = None
    arxiv_id: str | None = None
    openalex_id: str | None = None
    s2_id: str | None = None
    citation_count: int | None = None
    links: dict[str, str] = field(default_factory=dict)
    oa_pdf_url: str | None = None
    work_type: str | None = None
    raw: dict[str, Any] = field(default_factory=dict, repr=False, compare=False)


@dataclass(frozen=True, slots=True)
class Page:
    """One page of search results.

    ``total`` is the number of matches the source reports (it may be far larger than
    what can be paged through). ``next_offset`` is where to continue, or ``None`` when
    there is nothing more to fetch.
    """

    items: list[PaperMeta]
    total: int | None = None
    next_offset: int | None = None


@dataclass(frozen=True, slots=True)
class MergedPaper:
    """One paper after de-duplication: display fields plus every source record.

    Display fields prefer the formally published record; ``records`` keeps all versions
    and sources (SPEC §5.2). ``status`` is ``"published"``, ``"preprint"`` or
    ``"unknown"``. Like ``PaperMeta``, nothing here is generated by a model.
    """

    title: str
    abstract: str | None
    authors: tuple[str, ...]
    year: int | None
    date: str | None
    venue: str | None
    doi: str | None
    arxiv_id: str | None
    openalex_id: str | None
    s2_id: str | None
    citation_count: int | None
    links: dict[str, str]
    oa_pdf_url: str | None
    work_type: str | None
    status: str
    records: tuple[PaperMeta, ...]


def paper_to_dict(paper: PaperMeta) -> dict[str, Any]:
    """JSON-friendly form of a record without its bulky ``raw`` payload."""
    data = asdict(paper)
    data.pop("raw")
    data["authors"] = list(paper.authors)
    return data


def paper_from_dict(data: dict[str, Any]) -> PaperMeta:
    """Inverse of ``paper_to_dict`` (``raw`` is not restored)."""
    fields = dict(data)
    fields["authors"] = tuple(fields.get("authors") or ())
    return PaperMeta(**fields)
